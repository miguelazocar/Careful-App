/**
 * Android Auto Backup rules for Careful.
 *
 * Android backs up app data to the user's Google account (Google One / Drive) and restores it
 * when the app is reinstalled. We include:
 *   - the SQLite database (files/SQLite/*)
 *   - shared preferences
 * and exclude:
 *   - expo-secure-store values (bound to this device's Keystore; unusable elsewhere)
 *   - photos (they can exceed the 25 MB quota and break the whole backup) — photos travel in
 *     Careful's own .zip backups instead.
 *
 * expo-secure-store's own backup rules are disabled in app.json (configureAndroidBackup: false)
 * so the two plugins don't fight over android:fullBackupContent / dataExtractionRules.
 */
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const FULL_BACKUP = `<?xml version="1.0" encoding="utf-8"?>
<!-- Auto Backup for Android 11 and lower (generated by plugins/with-android-backup-rules.js) -->
<full-backup-content>
  <include domain="file" path="SQLite/" />
  <include domain="sharedpref" path="." />
  <exclude domain="sharedpref" path="SecureStore" />
</full-backup-content>
`;

const EXTRACTION_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Auto Backup for Android 12+ (generated by plugins/with-android-backup-rules.js) -->
<data-extraction-rules>
  <cloud-backup>
    <include domain="file" path="SQLite/" />
    <include domain="sharedpref" path="." />
    <exclude domain="sharedpref" path="SecureStore" />
  </cloud-backup>
  <device-transfer>
    <include domain="file" path="SQLite/" />
    <include domain="file" path="photos/" />
    <include domain="sharedpref" path="." />
    <exclude domain="sharedpref" path="SecureStore" />
  </device-transfer>
</data-extraction-rules>
`;

function withBackupXml(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'careful_backup_rules.xml'), FULL_BACKUP);
      fs.writeFileSync(path.join(dir, 'careful_data_extraction_rules.xml'), EXTRACTION_RULES);
      return cfg;
    },
  ]);
}

function withBackupManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0];
    if (app) {
      app.$['android:allowBackup'] = 'true';
      app.$['android:fullBackupContent'] = '@xml/careful_backup_rules';
      app.$['android:dataExtractionRules'] = '@xml/careful_data_extraction_rules';
    }
    return cfg;
  });
}

module.exports = function withAndroidBackupRules(config) {
  return withBackupManifest(withBackupXml(config));
};
